plugins {
    id("org.jetbrains.kotlin.jvm")
}

java {
    sourceCompatibility = JavaVersion.VERSION_17
    targetCompatibility = JavaVersion.VERSION_17
}

kotlin {
    compilerOptions {
        jvmTarget.set(org.jetbrains.kotlin.gradle.dsl.JvmTarget.JVM_17)
    }
}

dependencies {
    // The core is pure Kotlin: no Android, no sherpa-onnx, no dependencies at
    // all beyond the stdlib. That is what lets it be tested on the JVM and
    // what makes the port to the Windows implementation verifiable.
    testImplementation(kotlin("test"))
    testImplementation("com.google.code.gson:gson:2.11.0")
}

tasks.test {
    useJUnitPlatform()
    testLogging {
        events("passed", "failed", "skipped")
        exceptionFormat = org.gradle.api.tasks.testing.logging.TestExceptionFormat.FULL
        showStandardStreams = false
    }
}

/**
 * The parity corpus, generated by the Python implementation in
 * darts-coach-windows.
 *
 * It lives outside this module, at the repository root, because it is
 * generated by the *other* repository and is shared between the two. It is
 * added to the test runtime classpath rather than copied, so there is one
 * copy and it cannot drift.
 */
val parityCorpus = rootProject.file("corpus")

tasks.test {
    dependsOn("syncParityCorpus")
    systemProperty(
        "parity.corpus.dir",
        layout.buildDirectory.dir("parity-corpus").get().asFile.absolutePath,
    )
}

/**
 * Copy the corpus into the build directory so the test reads a stable
 * snapshot. The source directory is outside the module, so Gradle would
 * otherwise not track it as an input and the tests would not re-run when the
 * corpus changes.
 */
val syncParityCorpus by tasks.registering(Copy::class) {
    from(parityCorpus) {
        include("*.json")
    }
    into(layout.buildDirectory.dir("parity-corpus"))
}